/** Position group label for display */
export function positionGroup(pos: string): string {
  if (pos === "GK") return "Goalkeeper";
  if (["CB", "LB", "RB", "LWB", "RWB"].includes(pos)) return "Defender";
  if (["CDM", "CM", "CAM"].includes(pos)) return "Midfielder";
  return "Forward";
}

